/**
 * Lock-screen (secure) camera contract for the Alpha AOSP image (policy P-23, issue #407).
 *
 * Alpha does not implement its own secure camera. The image keeps the AOSP system
 * camera (Camera2, package com.android.camera2) and its SecureCameraActivity, which
 * Keyguard and the double-press power-key gesture launch while the device is locked.
 * That activity shows only captures from the current locked session; the gallery,
 * Alpha's agent, accounts and app navigation stay behind unlock.
 *
 * Three parts, each with a different strength of evidence:
 *  - staging output (product.mk lines and a framework resource overlay);
 *  - an APK admission check that refuses an Alpha APK which would put any of its own
 *    surfaces over the lock screen or claim the secure-camera intents;
 *  - a read-only adb admission of a booted image (handler routing, gesture setting,
 *    camera presence). It never proves locked capture, isolation or unlock/return
 *    behaviour, which need a person on the physical device.
 */
import fs from "node:fs";
import path from "node:path";
import { manifestComponents } from "./aosp-provisioning-overlay.mjs";

export const systemCameraPackage = "com.android.camera2";
/** MediaStore.INTENT_ACTION_STILL_IMAGE_CAMERA_SECURE and ACTION_IMAGE_CAPTURE_SECURE. */
export const secureCameraActions = [
  "android.media.action.STILL_IMAGE_CAMERA_SECURE",
  "android.media.action.IMAGE_CAPTURE_SECURE",
];
/** Manifest attributes that put an activity above Keyguard. */
export const lockScreenAttributes = ["showWhenLocked", "showOnLockScreen", "turnScreenOn"];
const TRUE = "0xffffffff";

const overlayPath = "secure-camera/overlay/frameworks/base/core/res/res/values/config.xml";

export function renderSecureCameraOverlay() {
  return {
    [overlayPath]: `<?xml version="1.0" encoding="utf-8"?>
<!-- Alpha Phone secure camera (policy P-23). Generated by scripts/stage-aosp.mjs. -->
<!-- Keep the system double-press power-key camera gesture available on the lock screen. -->
<!-- The user can still turn it off in Settings (Settings.Secure.CAMERA_DOUBLE_TAP_POWER_GESTURE_DISABLED). -->
<resources>
    <bool name="config_cameraDoubleTapPowerGestureEnabled">true</bool>
</resources>
`,
    "secure-camera/README.md": `# Alpha Phone secure camera

Generated by \`scripts/stage-aosp.mjs\` (policy P-23, issue #407).

- The AOSP system camera (\`Camera2\`, \`${systemCameraPackage}\`) is required in the image.
  Its \`SecureCameraActivity\` handles \`${secureCameraActions.join("` and `")}\`.
- \`config_cameraDoubleTapPowerGestureEnabled\` stays \`true\`, so a double press of the
  power key opens the secure camera over Keyguard where the hardware supports it.
- Alpha Phone declares no secure-camera handler and no activity shown over the lock
  screen; staging refuses an APK that does.

Confirm the overlay resource name against the pinned Android source when the image
is built. Staging output proves neither the gesture, locked capture isolation nor
unlock and return behaviour: those are device acceptance gates.
`,
    productMakefile: `
# Alpha Phone keeps the system secure camera on the lock screen (policy P-23, issue #407).
# Alpha never handles the secure-camera intents; Keyguard and the power-key gesture launch
# the AOSP camera's SecureCameraActivity, which shows only that locked session's captures.
PRODUCT_PACKAGES += Camera2
alphaphone_secure_camera_dir := $(patsubst %/,%,$(dir $(lastword $(MAKEFILE_LIST))))/secure-camera
PRODUCT_PACKAGE_OVERLAYS += $(alphaphone_secure_camera_dir)/overlay
`,
  };
}

export function writeSecureCameraOverlay(output) {
  const files = renderSecureCameraOverlay();
  for (const [name, content] of Object.entries(files)) {
    if (name === "productMakefile") continue;
    const file = path.join(output, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, { flag: "wx" });
  }
  fs.appendFileSync(path.join(output, "product.mk"), files.productMakefile);
  return files;
}

/**
 * Refuse an Alpha APK (from `aapt dump xmltree`) that would show any of its own
 * activities over Keyguard or register for the secure-camera intents. Locked capture
 * belongs to the system camera only, so no Alpha surface, agent or account UI can run
 * above the lock screen.
 */
export function assertNoAlphaLockScreenSurface(xmltree) {
  const problems = [];
  for (const row of manifestComponents(xmltree)) {
    if (row.tag === "service") continue;
    for (const attr of lockScreenAttributes)
      if (row.attrs[attr] === TRUE) problems.push(`${row.name} sets android:${attr}`);
    for (const filter of row.filters)
      for (const action of filter.actions)
        if (secureCameraActions.includes(action)) problems.push(`${row.name} handles ${action}`);
  }
  if (problems.length)
    throw new Error(`Refusing the APK: Alpha does not implement a secure camera or lock-screen surface (policy P-23).\n${problems.map(p => `  - ${p}`).join("\n")}`);
  return true;
}

const user = value => {
  if (!/^(0|[1-9]\d*)$/.test(value || "")) throw Error("Explicit Android user required");
  return value;
};

/**
 * Read-only admission of a booted image over adb. `run(...args)` executes
 * `adb -s SERIAL ...args` and returns stdout. Handler routing does not prove that a
 * locked capture works or stays isolated; the verified flags below stay false.
 */
export function verifyAospSecureCamera(run, androidUser, alphaPackage) {
  const u = user(androidUser);
  if (!/^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+$/.test(alphaPackage || "")) throw Error("Alpha package required");
  const cameraPresent = run("shell", "pm", "has-feature", "android.hardware.camera.any").trim() === "true";
  const installed = run("shell", "pm", "list", "packages", "--user", u, "-e", systemCameraPackage);
  const systemCameraEnabled = installed.split(/\r?\n/).includes(`package:${systemCameraPackage}`);
  if (!systemCameraEnabled) throw Error(`Required AOSP system camera ${systemCameraPackage} is not enabled for the selected user`);
  const handlers = {};
  for (const action of secureCameraActions) {
    const output = run("shell", "cmd", "package", "query-activities", "--brief", "--components", "--user", u, "-a", action);
    const rows = output.trim().split(/\r?\n/).map(line => line.trim()).filter(line => /^[A-Za-z0-9_.]+\/[A-Za-z0-9_.$]+$/.test(line));
    const alpha = rows.filter(row => row.startsWith(`${alphaPackage}/`));
    if (alpha.length) throw Error(`Alpha must not handle ${action}: ${alpha.join(", ")}`);
    handlers[action] = rows;
  }
  const still = handlers[secureCameraActions[0]];
  if (cameraPresent && !still.some(row => row.startsWith(`${systemCameraPackage}/`)))
    throw Error(`The system camera does not handle ${secureCameraActions[0]}; the lock screen has no secure camera entry`);
  const setting = run("shell", "settings", "get", "--user", u, "secure", "camera_double_tap_power_gesture_disabled").trim();
  return {
    user: u,
    cameraPresent,
    systemCameraPackage,
    handlers,
    // "null" means the image default (enabled); "1" means the user turned the gesture off.
    powerGestureDisabledByUser: setting === "1",
    lockedCaptureVerified: false,
    isolationVerified: false,
    unlockReturnVerified: false,
  };
}
