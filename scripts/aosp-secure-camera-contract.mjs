export function writeSecureCameraOverlay(output) {
  const files = renderSecureCameraOverlay();
  for (const [name, content] of Object.entries(files)) {
    if (name === "productMakefile") continue;
    const file = path.join(output, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, { flag: "wx" });
  }
  fs.appendFileSync(path.join(output, "product.mk"), files.productMakefile);
  return files;
}

/**
 * Method names referenced from dex bytes. A dex string_data_item is a ULEB128 UTF-16
 * length followed by MUTF-8 bytes and a NUL, so an exact entry is the name with its
 * length byte before it and a NUL after it (all names here are ASCII and under 128).
 */
export function dexLockScreenReferences(dex) {
  const found = [];
  for (const name of lockScreenMethods) {
    const needle = Buffer.from(name, "ascii");
    for (let at = dex.indexOf(needle); at >= 0; at = dex.indexOf(needle, at + 1))
      if (at > 0 && dex[at - 1] === needle.length && dex[at + needle.length] === 0) { found.push(name); break; }
  }
  return found;
}

/**
 * Refuse an Alpha APK that would show any of its own activities over Keyguard or
 * register for the secure-camera intents. `xmltree` is `aapt dump xmltree` of its
 * manifest; `dex` (optional) is the concatenated bytes of its classes*.dex. Any
 * lock-screen attribute whose value is not literally false is refused, including a
 * resource reference (`@0x7f...`) whose value aapt cannot show.
 */
export function assertNoAlphaLockScreenSurface(xmltree, dex = null) {
  const problems = [];
  for (const row of manifestComponents(xmltree)) {
    if (row.tag === "service") continue;
    for (const attr of lockScreenAttributes)
      if (attr in row.attrs && row.attrs[attr] !== FALSE) problems.push(`${row.name} sets android:${attr}=${row.attrs[attr]}`);
    for (const filter of row.filters)
      for (const action of filter.actions)
        if (secureCameraActions.includes(action)) problems.push(`${row.name} handles ${action}`);
  }
  if (dex) for (const name of dexLockScreenReferences(dex)) problems.push(`dex references ${name}`);
  if (problems.length)
    throw new Error(`Refusing the APK: Alpha does not implement a secure camera or lock-screen surface (policy P-23).\n${problems.map(p => `  - ${p}`).join("\n")}`);
  return true;
}

const user = value => {
  if (!/^(0|[1-9]\d*)$/.test(value || "")) throw Error("Explicit Android user required");
  return value;
};

/**
 * `pm has-feature` prints false and exits 1 when the feature is absent
 * (PackageManagerShellCommand.runHasFeature), and adb passes that status through.
 */
export function hasFeature(run, feature) {
  let out;
  try {
    out = run("shell", "pm", "has-feature", feature);
  } catch (error) {
    if (error?.status === 1 && String(error.stdout ?? "").trim() === "false") return false;
    throw error;
  }
  const value = String(out).trim();
  if (value !== "true" && value !== "false") throw Error(`Unexpected pm has-feature output: ${value}`);
  return value === "true";
}

/**
 * Grant state of one runtime permission for one user, from `dumpsys package PKG`.
 * Returns true, false or null when the user's block lists no such permission.
 */
export function runtimePermissionGranted(dumpsys, androidUser, permission) {
  const lines = dumpsys.split(/\r?\n/);
  const start = lines.findIndex(line => new RegExp(`^\\s*User ${androidUser}:`).test(line));
  if (start < 0) return null;
  const indent = /^\s*/.exec(lines[start])[0].length;
  for (const line of lines.slice(start + 1)) {
    if (line.trim() && /^\s*/.exec(line)[0].length <= indent) break;
    const match = new RegExp(`^\\s*${permission.replaceAll(".", "\\.")}: granted=(true|false)`).exec(line);
    if (match) return match[1] === "true";
  }
  return null;
}

/**
 * Read-only admission of a booted image over adb. `run(...args)` executes
 * `adb -s SERIAL ...args` and returns stdout (throwing like execFileSync on a non-zero
 * exit). It reports routing of the two secure intents only, not what Keyguard's
 * quick affordance or the gesture launch; the verified flags below stay false.
 */
export function verifyAospSecureCamera(run, androidUser, alphaPackage) {
  const u = user(androidUser);
  if (!/^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+$/.test(alphaPackage || "")) throw Error("Alpha package required");
  // Camera2 is not direct-boot aware: before the first unlock its secure entry cannot resolve.
  const credentialStorage = run("shell", "getprop", `sys.user.${u}.ce_available`).trim();
  if (credentialStorage !== "true") throw Error(`Unlock Android user ${u} once after boot before this admission (sys.user.${u}.ce_available=${credentialStorage || "unset"})`);
  const cameraPresent = hasFeature(run, "android.hardware.camera.any");
  const installed = run("shell", "pm", "list", "packages", "--user", u, "-e", systemCameraPackage);
  const systemCameraEnabled = installed.split(/\r?\n/).includes(`package:${systemCameraPackage}`);
  if (!systemCameraEnabled) throw Error(`Required AOSP system camera ${systemCameraPackage} is not enabled for the selected user`);
  const systemCameraPermissionGranted = runtimePermissionGranted(run("shell", "dumpsys", "package", systemCameraPackage), u, "android.permission.CAMERA");
  const handlers = {};
  for (const action of secureCameraActions) {
    const output = run("shell", "cmd", "package", "query-activities", "--brief", "--components", "--user", u, "-a", action, "-c", "android.intent.category.DEFAULT");
    const rows = output.trim().split(/\r?\n/).map(line => line.trim()).filter(line => /^[A-Za-z0-9_.]+\/[A-Za-z0-9_.$]+$/.test(line));
    const alpha = rows.filter(row => row.startsWith(`${alphaPackage}/`));
    if (alpha.length) throw Error(`Alpha must not handle ${action}: ${alpha.join(", ")}`);
    handlers[action] = rows;
  }
  const still = handlers[secureCameraActions[0]];
  if (cameraPresent && !still.some(row => row.startsWith(`${systemCameraPackage}/`)))
    throw Error(`The system camera does not handle ${secureCameraActions[0]}; the secure intent has no system camera route`);
  const setting = key => run("shell", "settings", "get", "--user", u, "secure", key).trim();
  const cameraGestureDisabled = setting("camera_double_tap_power_gesture_disabled");
  const gestureEnabled = setting("double_tap_power_button_gesture_enabled");
  const gestureTarget = setting("double_tap_power_button_gesture");
  return {
    user: u,
    cameraPresent,
    systemCameraPackage,
    // null: the user's dumpsys block lists no CAMERA grant; false: denied, so a locked
    // capture would prompt over Keyguard or fail.
    systemCameraPermissionGranted,
    secureIntentHandlers: handlers,
    // "null" means the image default. Which key the pinned Android 17 GestureLauncherService
    // reads is unconfirmed (#399); AOSP main reads camera_double_tap_power_gesture_disabled.
    powerGestureSettings: {
      camera_double_tap_power_gesture_disabled: cameraGestureDisabled,
      double_tap_power_button_gesture_enabled: gestureEnabled,
      double_tap_power_button_gesture: gestureTarget,
    },
    powerGestureDisabledByUser: cameraGestureDisabled === "1" || gestureEnabled === "0",
    powerGestureTargetsWallet: gestureTarget === "1",
    keyguardAffordanceVerified: false,
    lockedCaptureVerified: false,
    isolationVerified: false,
    unlockReturnVerified: false,
  };
}
