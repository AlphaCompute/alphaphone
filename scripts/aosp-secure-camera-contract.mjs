/**
 * Lock-screen (secure) camera contract for the Alpha AOSP image (policy P-23, issue #407).
 *
 * Alpha does not implement its own secure camera. The image is meant to keep the AOSP
 * system camera (Camera2, package com.android.camera2) and its SecureCameraActivity,
 * which Keyguard and the double-press power-key gesture launch while the device is
 * locked. That activity shows only captures from the current locked session; the
 * gallery, Alpha's agent, accounts and app navigation stay behind unlock.
 *
 * Three parts, each with a different strength of evidence:
 *  - staging output (product.mk lines and a framework resource overlay). The resource
 *    and Settings names were checked against public AOSP main
 *    (platform/frameworks/base 1cdfff555f4a, 2026-10-12), not against the pinned
 *    Android 17 / Pixel 10a source, which #399 has not admitted yet;
 *  - an APK admission check that refuses an Alpha APK whose manifest would put any of
 *    its own activities over the lock screen or claim the secure-camera intents, or
 *    whose dex references the runtime Keyguard APIs by name. Flag constants such as
 *    FLAG_SHOW_WHEN_LOCKED are inlined integers and reflective calls carry no method
 *    reference, so neither is detectable by this scan;
 *  - a read-only adb admission of a booted image: routing of the two secure intents,
 *    camera presence, the system camera's CAMERA grant and the double-press power
 *    settings. It does not read what Keyguard's quick affordance or the gesture
 *    actually launch, and never proves locked capture, isolation or unlock/return
 *    behaviour, which need a person on the physical device.
 */
import fs from "node:fs";
import path from "node:path";
import { manifestComponents } from "./aosp-provisioning-overlay.mjs";

export const systemCameraPackage = "com.android.camera2";
/** MediaStore.INTENT_ACTION_STILL_IMAGE_CAMERA_SECURE and ACTION_IMAGE_CAPTURE_SECURE. */
export const secureCameraActions = [
  "android.media.action.STILL_IMAGE_CAMERA_SECURE",
  "android.media.action.IMAGE_CAPTURE_SECURE",
];
/** Manifest attributes that put an activity above Keyguard. */
export const lockScreenAttributes = ["showWhenLocked", "showOnLockScreen", "turnScreenOn"];
/** Framework methods that put an activity above Keyguard or dismiss it at runtime. */
export const lockScreenMethods = ["setShowWhenLocked", "setTurnScreenOn", "requestDismissKeyguard"];
/** The only accepted value of a lock-screen attribute: a literal false. */
const FALSE = "0x0";

const overlayPath = "secure-camera/overlay/frameworks/base/core/res/res/values/config.xml";

